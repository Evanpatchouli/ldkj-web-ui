import { promises as fs } from "node:fs";
import path from "node:path";
import process from "node:process";
import { enabledIconNames } from "./enabled-material-symbol-names.mjs";

const variants = ["outlined", "rounded", "sharp"];
const packageName = "@material-symbols/svg-400";
const rootDir = process.cwd();
const iconsRoot = path.join(rootDir, "node_modules", packageName);
const outputPath = path.join(
  rootDir,
  "src/components/data-display/icon/loaders.ts",
);

function stableSort(list) {
  return [...list].sort((a, b) => a.localeCompare(b));
}

async function getVariantIconNames(variant) {
  const dir = path.join(iconsRoot, variant);
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const names = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".svg"))
    .map((entry) => entry.name.replace(/\.svg$/u, ""));
  return stableSort(names);
}

function createHeader() {
  return `/* eslint-disable */
/* AUTO-GENERATED FILE. DO NOT EDIT.
 * Generated by scripts/generate-material-symbol-loaders.mjs
 */
import type * as React from "react";

export type SvgIconModule = {
  default: React.ComponentType<React.SVGProps<SVGSVGElement> & { title?: string }>;
};

export type IconLoader = () => Promise<SvgIconModule>;

type IconVariantLoaders = {
  outlined: IconLoader;
  rounded?: IconLoader;
  sharp?: IconLoader;
};

`;
}

function createLoaderImportLine(variant, iconName) {
  return `() => import("${packageName}/${variant}/${iconName}.svg?react")`;
}

function createRecordBody(allIconNames, variantNameSets) {
  const lines = [];
  for (const iconName of allIconNames) {
    const outlinedExists = variantNameSets.outlined.has(iconName);
    if (!outlinedExists) {
      continue;
    }
    const roundedExists = variantNameSets.rounded.has(iconName);
    const sharpExists = variantNameSets.sharp.has(iconName);

    lines.push(`  ${JSON.stringify(iconName)}: {`);
    lines.push(
      `    outlined: ${createLoaderImportLine("outlined", iconName)},`,
    );
    lines.push(
      `    rounded: ${
        roundedExists
          ? createLoaderImportLine("rounded", iconName)
          : createLoaderImportLine("outlined", iconName)
      },`,
    );
    lines.push(
      `    sharp: ${
        sharpExists
          ? createLoaderImportLine("sharp", iconName)
          : createLoaderImportLine("outlined", iconName)
      },`,
    );
    lines.push("  },");
  }
  return lines.join("\n");
}

async function main() {
  const variantMap = {};
  for (const variant of variants) {
    variantMap[variant] = await getVariantIconNames(variant);
  }

  const dedupedEnabledNames = Array.from(new Set(enabledIconNames));
  const duplicateCount = enabledIconNames.length - dedupedEnabledNames.length;

  const variantNameSets = {
    outlined: new Set(variantMap.outlined),
    rounded: new Set(variantMap.rounded),
    sharp: new Set(variantMap.sharp),
  };
  const existingNames = stableSort(
    dedupedEnabledNames.filter((name) => variantNameSets.outlined.has(name)),
  );
  const missingNames = stableSort(
    dedupedEnabledNames.filter((name) => !variantNameSets.outlined.has(name)),
  );

  const content =
    createHeader() +
    `/**\n * 注册式图标加载表（按 enabledIconNames 白名单生成）。\n */\n` +
    `export const materialSymbolLoaders: Record<string, IconVariantLoaders> = {\n` +
    createRecordBody(existingNames, variantNameSets) +
    "\n};\n";

  await fs.writeFile(outputPath, content, { encoding: "utf8" });
  // eslint-disable-next-line no-console
  console.log(
    `Generated ${path.relative(rootDir, outputPath)} with ${existingNames.length} icons.`,
  );
  // eslint-disable-next-line no-console
  console.log(
    `Input names: ${enabledIconNames.length}, deduped: ${dedupedEnabledNames.length}, duplicates removed: ${duplicateCount}.`,
  );
  if (missingNames.length > 0) {
    // eslint-disable-next-line no-console
    console.warn(
      `Skipped ${missingNames.length} names not found in outlined variant: ${missingNames.join(", ")}`,
    );
  }
}

main().catch((error) => {
  // eslint-disable-next-line no-console
  console.error(error);
  process.exitCode = 1;
});
